#!/usr/bin/env python3
"""
Linear (least-squares) unmixing on a sample network.

This module implements the linear formulation described in Appendix A of the funmixer
preprint. Where :class:`~funmixer.network_unmixer.SampleNetworkUnmixer` penalises *relative*
differences between predicted and observed concentrations (a convex surrogate for the
log-ratio misfit), this module penalises *absolute* differences. That choice is appropriate
when the tracer has low log-variance and it turns the whole problem into a linear system.

The forward model
-----------------
The observation at site ``i`` is a flux-weighted mixture of the source concentrations of every
sub-basin upstream of (and including) ``i``::

    d = M c,        M_ij = Theta_ij * alpha_{j->i} * q_j / Q_i

where ``Theta`` is the path matrix of the sample network with self-edges, ``q_j`` is the
material flux generated by sub-basin ``j``, ``Q_i = sum_j Theta_ij q_j`` is the total flux
passing site ``i``, and ``alpha_{j->i} = exp(-sum k*L)`` is the first-order decay accumulated
along the path from ``j`` to ``i``. Decay is applied to the tracer flux only and never to the
total flux, matching :func:`~funmixer.network_unmixer.forward_model`.

Why this is exactly soluble
---------------------------
funmixer defines exactly one sub-basin per sample site, so ``M`` is square (n x n). Ordered
topologically (upstream to downstream) it is **lower triangular with strictly positive
diagonal** ``M_ii = q_i / Q_i``, and is therefore always invertible. Two consequences:

1. At ``lambda = 0`` the problem is not really least-squares at all -- it has an exact,
   zero-residual solution ``c = M^-1 d``. There is no pseudo-inverse ambiguity, and weighted
   (GLS) variants collapse to the same estimator, so "the estimator used when unconstrained"
   is unambiguous. The inverse has a sparse closed form::

       c_i = ( Q_i d_i - sum_{p in direct upstream nbrs of i} alpha_p Q_p d_p ) / q_i

   i.e. "tracer flux out, minus tracer flux in, over own flux".
2. The non-negativity constraint bites *exactly* when ``Q_i d_i < sum_p alpha_p Q_p d_p`` --
   when a site carries less tracer flux than its own tributaries deliver. That is precisely
   where the method breaks down, and it is directly checkable via
   :attr:`LinearFunmixerSolution.unconstrained_preds`.

The per-node noise amplification of the inversion is ``1 / M_ii = Q_i / q_i``. A sample taken
just downstream of another, with little incremental drainage area between them, has a large
amplification factor and will be poorly resolved. This -- the disparity in *sub-basin areas* --
is the real control on whether the linear approach is usable for a given network, and it is
reported as :attr:`LinearFunmixerSolution.amplification`.

Regularization
--------------
Optionally we penalise the variance of ``c``, i.e. deviations of ``c`` from its *own* mean::

    minimize  (M c - d)^T C_d^-1 (M c - d)  +  lambda ||P c||^2      subject to  c >= 0

(the misfit term is ``||M c - d||^2`` when the solve is unweighted)

with ``P = I - (1/n) 1 1^T`` the centering projector, so that ``||P c||^2 = sum_i (c_i -
c_bar)^2 = n * var(c)``. Note lambda therefore weights the *sum* of squared deviations rather
than their mean, so a factor of ``n`` is absorbed into it. Note also this differs deliberately
from
:class:`SampleNetworkUnmixer`, which is forced by convexity to shrink towards the mean
*observation*; the linear form has no such constraint and can shrink towards the mean *model*.

A solution is guaranteed for every ``lambda >= 0``: the Hessian is ``2(M^T M + lambda P)``, and
although ``P`` alone is only positive semi-definite (its null space is ``span{1}``), ``M^T M``
is positive definite because ``M`` is invertible. The objective is therefore strictly convex,
giving a unique global minimiser, and it stays unique under ``c >= 0``. Regularization strictly
improves the conditioning, so ``lambda > 0`` is always better behaved than ``lambda = 0``.
Uniqueness does rest on ``M`` being invertible -- ``lambda P`` could not rescue a singular
``M`` on its own.

Error propagation
-----------------
Because ``||P c||^2`` is homogeneous in ``c``, the estimator carries **no constant offset** and
is purely linear in the data::

    c_hat  = R d,     R = (M^T M + lambda P)^-1 M^T
    C_c    = R C_d R^T       (covariance of the recovered source concentrations)
    C_dhat = M C_c M^T       (covariance of the modelled observations)

At ``lambda = 0`` this reduces to ``M^-1 C_d M^-T`` exactly, so the regularized and
unregularized cases share a single code path. Likewise the modelled-observation covariance
reduces to ``C_d`` itself at ``lambda = 0``, since the fit is exact there.

At ``lambda = 0`` the estimator is unbiased and ``C_c`` is the complete error. It also equals
``(M^T C_d^-1 M)^-1``, the Cramer-Rao lower bound, so the unregularized inversion is an
efficient estimator and no weighting can improve on it.

Once ``lambda > 0`` the estimator is **biased**, and two different covariances become relevant.
Both are reported:

* ``upstream_covariance``: the *propagated* (sampling) covariance ``R C_d R^T``. This answers
  "if I repeated the measurements, how would my estimate scatter?" It is exactly the linear
  propagation of ``C_d`` through the estimator actually used -- but it **shrinks as lambda
  grows**, because a more heavily damped estimator is more stable while being more wrong. Used
  alone at large lambda it badly understates the true error.
* ``upstream_posterior_covariance``: ``(M^T C_d^-1 M + lambda P)^-1``, the Bayesian posterior
  covariance obtained by reading the penalty as a prior. This accounts for what the damping
  costs as well as what it stabilises, and is the more honest error bar to quote at
  ``lambda > 0``. The two are related exactly by::

      R C_d R^T = (M^T C_d^-1 M + lambda P)^-1 - lambda A^-1 P A^-1,   A = M^T C_d^-1 M + lambda P

  so the propagated covariance is always the smaller of the two, and they coincide at
  ``lambda = 0``.

The remaining, unquantifiable piece is the bias itself,
``bias = -lambda A^-1 P c_true``, which needs the unknown ``c_true``. As a proxy we report the
resolution matrix ``R M`` (the identity at ``lambda = 0``, degrading as ``lambda`` grows) and
its trace, the effective number of degrees of freedom.

References
----------
These are standard results in discrete linear inverse theory; the notation below follows the
first two.

* Menke, W., *Geophysical Data Analysis: Discrete Inverse Theory*. Weighted least squares,
  damped least squares, and the two results used most directly here: for any linear estimator
  ``m_est = G^-g d`` the model covariance is ``C_m = G^-g C_d G^-g^T``, and the model
  resolution matrix is ``R = G^-g G``.
* Aster, R., Borchers, B. and Thurber, C., *Parameter Estimation and Inverse Problems*.
  Tikhonov regularization, the L-curve, resolution, and the bias-variance decomposition of the
  regularized solution -- i.e. why the propagated covariance is not the whole error.
* Tarantola, A. (2005), *Inverse Problem Theory and Methods for Model Parameter Estimation*,
  SIAM. The linear-Gaussian case, where the posterior covariance is
  ``(G^T C_d^-1 G + C_m^-1)^-1``; this is the source of `upstream_posterior_covariance`.
* Hoerl, A. E. and Kennard, R. W. (1970), "Ridge Regression: Biased Estimation for
  Nonorthogonal Problems", *Technometrics* 12(1), 55-67. The original bias-variance argument
  for penalised estimators.
* Hansen, P. C. (1998), *Rank-Deficient and Discrete Ill-Posed Problems*, SIAM. Filter factors,
  the L-curve, and general-form (seminorm) Tikhonov regularization -- the case here, since the
  penalty operator ``P`` is singular. The uniqueness condition for general-form Tikhonov is
  that the null spaces of the forward and penalty operators intersect only at zero, which
  holds here because ``M`` is invertible. See also Elden, L. (1977), "Algorithms for the
  regularization of ill-conditioned least squares problems", *BIT* 17, 134-145.
* Golub, G. H. and Van Loan, C. F., *Matrix Computations*, for the numerical treatment of
  generalised least squares via whitening, and of Tikhonov problems via augmented systems.
"""

